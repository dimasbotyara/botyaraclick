def get_theme(theme_id: str) -> dict:
    """Возвращает данные темы по ID."""
    return THEMES.get(theme_id, THEMES["default"])


def get_purchasable_themes() -> list:
    """Возвращает список тем, которые можно купить (кроме default)."""
    return [t for t_id, t in THEMES.items() if t["cost"] > 0]

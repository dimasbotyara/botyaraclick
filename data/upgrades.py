def get_upgrades_by_category(category: str) -> list:
    """Возвращает все улучшения в данной категории."""
    return [u for u in ALL_UPGRADES_LIST if u["category"] == category]

def get_upgrades_by_branch(category: str, branch: str) -> list:
    """Возвращает все улучшения в данной ветке."""
    return [u for u in ALL_UPGRADES_LIST
            if u["category"] == category and u["branch"] == branch]

def get_upgrade_cost(upgrade_data: dict, count_owned: int) -> float:
    """Рассчитывает стоимость следующей покупки улучшения."""
    from config import PRICE_MULTIPLIER
    if upgrade_data["max_count"] == 1:
        return upgrade_data["base_cost"]
    return upgrade_data["base_cost"] * (PRICE_MULTIPLIER ** count_owned)
